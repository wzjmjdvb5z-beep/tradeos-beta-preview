const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('app/schedule-board.js','utf8').replace("  if(document.readyState==='loading')", "  globalThis.testSchedule={setContext(value){ctx=value;},getVisibleJobs,renderUnscheduled};\n  if(document.readyState==='loading')");
const sandbox={window:{},document:{readyState:'loading',addEventListener(){}},Intl,Date};
vm.runInNewContext(source,sandbox);
const api=sandbox.testSchedule;
const jobs=[{id:'assigned',title:'Assigned <job>'},{id:'other',title:'Other job'}];
const ctx={mine:{id:'employee'},isManager:false,jobs,assignments:[{member_id:'employee',job_id:'assigned'}]};
api.setContext(ctx);
let visible=api.getVisibleJobs();
assert.equal(visible.length,1);
let html=api.renderUnscheduled(visible);
assert.match(html,/Awaiting dates/);
assert.match(html,/Assigned &lt;job&gt;/);
assert.doesNotMatch(html,/Other job|data-schedule-job/);
assert.match(html,/Date to be confirmed/);
api.setContext({...ctx,isManager:true});
visible=api.getVisibleJobs();
assert.equal(visible.length,2);
html=api.renderUnscheduled(visible);
assert.match(html,/data-schedule-job="assigned"/);
assert.match(html,/data-schedule-job="other"/);
console.log('Schedule visibility: assigned undated jobs visible to employees; manager scheduling preserved.');
